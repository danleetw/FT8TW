/* ── 手冊最後更新日期 ────────────────────────────────────────────
   取資產的 Last-Modified，也就是網站最後一次發布的時間，因此不需要
   有人記得手動改日期。以 file:// 開啟或請求失敗時回傳 null，呼叫端
   就不顯示日期——寧可不顯示，也不要顯示一個錯的日期。
   layout.js 與 print.js 都會用到，所以放在兩邊都會載入的這個檔案。 */
async function fetchManualUpdated() {
  try {
    const res = await fetch('assets/layout.js', { method: 'HEAD', cache: 'no-cache' });
    const lm = res.headers.get('Last-Modified');
    if (!lm) return null;
    const d = new Date(lm);
    if (isNaN(d.getTime())) return null;
    return `${d.getFullYear()}/${d.getMonth() + 1}/${d.getDate()}`;
  } catch (e) {
    return null;
  }
}
